def load_data(content_dir):
    data = {k: [] for k in LIST_KEYS}
    for f in sorted(glob.glob(os.path.join(content_dir, "*.yaml"))):
        with open(f, encoding="utf-8") as fh:
            doc = yaml.safe_load(fh) or {}
        for k in LIST_KEYS:
            data[k].extend(doc.get(k) or [])
    return data


