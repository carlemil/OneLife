def ink_from_white(rgb, color=INK):
    """White-background line art -> sepia ink on a transparent layer. Autocontrast
    first (so the lightest pixels become white), then drop near-white to fully
    transparent so only the inked lines remain (no muddy grey box)."""
    g = ImageOps.autocontrast(rgb.convert("L"), cutoff=1)
    cut = 198
    alpha = g.point(lambda L: 0 if L > cut else min(255, int(((cut - L) / cut) ** 0.8 * 300)))
    out = Image.new("RGBA", rgb.size, color + (0,))
    out.putalpha(alpha)
    return out


def procedural_icon(concept, size):
    """A crude but recognisable black-on-white doodle, used when AI is off/unreachable."""
    im = Image.new("RGB", (size, size), "white")
    d = ImageDraw.Draw(im)
    s = size
    w = max(3, s // 40)
    cx = s // 2
    def line(p, width=w): d.line(p, fill="black", width=width, joint="curve")
    if concept in ("forest", "park"):
        for i, x in enumerate((s*0.28, s*0.5, s*0.72)):
            top = s*(0.22 + 0.05*(i % 2)); base = s*0.82
            line([(x, top), (x, base)]);
            d.polygon([(x-s*0.13, base*0.78), (x, top), (x+s*0.13, base*0.78)], outline="black", width=w)
    elif concept == "church":
        d.rectangle([s*0.32, s*0.45, s*0.68, s*0.82], outline="black", width=w)
        d.polygon([(s*0.32, s*0.45), (s*0.5, s*0.28), (s*0.68, s*0.45)], outline="black", width=w)
        line([(s*0.5, s*0.1), (s*0.5, s*0.3)]); line([(s*0.42, s*0.18), (s*0.58, s*0.18)])
    elif concept in ("harbour",):
        line([(s*0.2, s*0.7), (s*0.8, s*0.7)])
        line([(s*0.5, s*0.2), (s*0.5, s*0.7)])
        d.polygon([(s*0.5, s*0.3), (s*0.74, s*0.55), (s*0.5, s*0.55)], outline="black", width=w)
        for y in (s*0.78, s*0.86): d.arc([s*0.2, y-12, s*0.4, y+12], 200, 340, fill="black", width=w)
    elif concept in ("lake", "park"):
        d.ellipse([s*0.2, s*0.45, s*0.8, s*0.72], outline="black", width=w)
    elif concept in ("castle",):
        d.rectangle([s*0.28, s*0.4, s*0.72, s*0.82], outline="black", width=w)
        for x in (0.28, 0.46, 0.62): d.rectangle([s*x, s*0.32, s*(x+0.1), s*0.42], outline="black", width=w)
    elif concept in ("tower",):
        d.rectangle([s*0.42, s*0.2, s*0.58, s*0.82], outline="black", width=w)
    elif concept in ("cemetery", "crypt"):
        for x in (0.3, 0.5, 0.7):
            d.rectangle([s*(x-0.07), s*0.5, s*(x+0.07), s*0.82], outline="black", width=w)
            d.arc([s*(x-0.07), s*0.43, s*(x+0.07), s*0.57], 180, 360, fill="black", width=w)
    elif concept in ("station",):
        d.rectangle([s*0.28, s*0.5, s*0.72, s*0.82], outline="black", width=w)
        d.line([(s*0.24, s*0.5), (s*0.76, s*0.5)], fill="black", width=w)
        d.ellipse([s*0.45, s*0.58, s*0.55, s*0.68], outline="black", width=w)
    else:  # house / village / manor / estate / generic
        d.rectangle([s*0.3, s*0.48, s*0.7, s*0.82], outline="black", width=w)
        d.polygon([(s*0.28, s*0.48), (s*0.5, s*0.3), (s*0.72, s*0.48)], outline="black", width=w)
        d.rectangle([s*0.44, s*0.62, s*0.56, s*0.82], outline="black", width=w)
    return im


def get_icon(concept, subject, cache_dir, use_ai, size=360):
    """Cache the RAW white-background art (so keying can be re-tuned without
    re-fetching); return it keyed to ink-on-transparent."""
    raw_path = os.path.join(cache_dir, f"{concept}.png")
    if os.path.exists(raw_path):
        try:
            return ink_from_white(Image.open(raw_path).convert("RGB"))
        except Exception:
            pass
    rgb = None
    if use_ai:
        prompt = (f"vintage fantasy map illustration of {subject}, pen and ink hand drawn "
                  "antique cartography symbol, dark sepia brown ink line art on plain solid "
                  "white background, centered, small, no text, no border, no shading, no colour")
        url = ("https://image.pollinations.ai/prompt/" + urllib.parse.quote(prompt)
               + f"?width={size}&height={size}&nologo=true&model=flux&seed={_seed(concept)}")
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "onelife-map/1"})
            raw = urllib.request.urlopen(req, timeout=90).read()
            rgb = Image.open(io.BytesIO(raw)).convert("RGB")
        except Exception as e:
            print(f"  [icon] {concept}: AI fetch failed ({e}); using fallback")
    if rgb is None:
        rgb = procedural_icon(concept, size)
    os.makedirs(cache_dir, exist_ok=True)
    rgb.save(raw_path)
    return ink_from_white(rgb)


