    ap.add_argument("--out", default=os.path.join(HERE, "..", "..", "..", "web", "public", "worldmap"))
    ap.add_argument("--no-ai", action="store_true", help="procedural icons only (offline)")
    ap.add_argument("--size", default="3200x2400", help="canvas WxH")
