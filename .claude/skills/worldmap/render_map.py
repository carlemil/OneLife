def parchment(W, H):
    base = Image.new("RGB", (W, H), PARCH)
    noise = Image.effect_noise((W, H), 22).convert("L")
    tint = Image.new("RGB", (W, H), PARCH_DARK)
    base = Image.composite(tint, base, noise.point(lambda v: int(v * 0.45)))
    # soft mottling
    blobs = Image.new("L", (W, H), 0)
    bd = ImageDraw.Draw(blobs)
    for i in range(40):
        r = _seed(f"blob{i}")
        x = r % W; y = (r // 7) % H; rad = 60 + (r % 240)
        bd.ellipse([x - rad, y - rad, x + rad, y + rad], fill=18)
    blobs = blobs.filter(ImageFilter.GaussianBlur(80))
    base = Image.composite(Image.new("RGB", (W, H), PARCH_DARK), base, blobs)
    # vignette
    vig = Image.new("L", (W, H), 0)
    vd = ImageDraw.Draw(vig)
    vd.rectangle([0, 0, W, H], fill=0)
    vd.ellipse([-W * 0.15, -H * 0.15, W * 1.15, H * 1.15], fill=255)
    vig = ImageOps.invert(vig.filter(ImageFilter.GaussianBlur(220)))
    base = Image.composite(Image.new("RGB", (W, H), (120, 96, 60)), base,
                           vig.point(lambda v: int(v * 0.5)))
    base = burnt_edges(base)
    return base.convert("RGBA")


def burnt_edges(base):
    """Char the parchment edges — an irregular scorched/blackened border."""
    W, H = base.size
    b = int(min(W, H) * 0.075)
    band = Image.new("L", (W, H), 0)
    bd = ImageDraw.Draw(band)
    bd.rectangle([0, 0, W, H], fill=255)
    bd.rectangle([b, b, W - b, H - b], fill=0)
    band = band.filter(ImageFilter.GaussianBlur(b * 0.55))
    noise = Image.effect_noise((W, H), 70)
    band = ImageChops.multiply(band, noise).point(lambda v: min(255, int(v * 3.2)))
    base = Image.composite(Image.new("RGB", (W, H), (46, 30, 16)), base, band)
    rim = Image.new("L", (W, H), 0)
    rd = ImageDraw.Draw(rim)
    rd.rectangle([0, 0, W, H], fill=255)
    rd.rectangle([int(b * 0.4), int(b * 0.4), int(W - b * 0.4), int(H - b * 0.4)], fill=0)
    rim = rim.filter(ImageFilter.GaussianBlur(b * 0.25))
    return Image.composite(Image.new("RGB", (W, H), (18, 11, 6)), base,
                           rim.point(lambda v: min(255, int(v * 1.6))))


def draw_rivers(base, W, H):
    """A couple of faint double-line ink rivers (always-on geography)."""
    rivers = [
        [(0.52, 0.04), (0.47, 0.18), (0.41, 0.33), (0.33, 0.47), (0.26, 0.6), (0.2, 0.72)],
        [(0.04, 0.8), (0.14, 0.84), (0.27, 0.81), (0.4, 0.87), (0.5, 0.84)],
    ]
    d = ImageDraw.Draw(base, "RGBA")
    for ri, river in enumerate(rivers):
        pts = []
        for i in range(len(river) - 1):
            seg = wobble((river[i][0] * W, river[i][1] * H),
                         (river[i + 1][0] * W, river[i + 1][1] * H),
                         min(W, H) * 0.012, 6, f"river{ri}-{i}")
            pts.extend(seg)
        for sign in (-1, 1):
            off = []
            for k in range(len(pts)):
                a = pts[max(0, k - 1)]; b = pts[min(len(pts) - 1, k + 1)]
                dx, dy = b[0] - a[0], b[1] - a[1]
                L = math.hypot(dx, dy) or 1
                off.append((pts[k][0] - dy / L * 6 * sign, pts[k][1] + dx / L * 6 * sign))
            d.line(off, fill=WATER_INK + (150,), width=4, joint="curve")


def draw_banner(text, font, w_pad=60):
    """A small ribbon banner tile with calligraphic text on parchment."""
    tmp = ImageDraw.Draw(Image.new("RGB", (4, 4)))
    tw = int(tmp.textlength(text, font=font)); th = font.getbbox("Ay")[3]
    W, H = tw + w_pad * 2, th + 36
    im = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(im, "RGBA")
    notch = 22
    d.polygon([(notch, 4), (W - notch, 4), (W - 4, H / 2), (W - notch, H - 4),
               (notch, H - 4), (4, H / 2)], fill=PARCH + (236,), outline=INK + (255,))
    d.line([(notch, 4), (4, H / 2), (notch, H - 4)], fill=INK + (255,), width=4)
    d.line([(W - notch, 4), (W - 4, H / 2), (W - notch, H - 4)], fill=INK + (255,), width=4)
    d.text((W / 2 - tw / 2, (H - th) / 2 - 2), text, font=font, fill=INK + (255,))
    return im


def terrain_patch(tile, concept, cx, cy, R):
    """Draw faint local terrain on a location tile, under the icon."""
    d = ImageDraw.Draw(tile, "RGBA")
    if concept in ("harbour",):
        d.ellipse([cx - R, cy + R*0.2, cx + R, cy + R*1.5], fill=WATER_INK + (70,))
        for k in range(3):
            yy = cy + R*0.6 + k*16
            d.arc([cx - R*0.7, yy-10, cx + R*0.7, yy+10], 200, 340, fill=INK_SOFT + (120,), width=3)
    elif concept in ("forest", "park"):
        d.ellipse([cx - R, cy - R*0.4, cx + R, cy + R], fill=FOREST + (60,))
    elif concept in ("lake",):
        d.ellipse([cx - R*0.9, cy + R*0.1, cx + R*0.9, cy + R], fill=WATER_INK + (70,))
    elif concept in ("village", "square", "estate", "house", "school"):
        d.ellipse([cx - R, cy - R*0.3, cx + R, cy + R], fill=FIELD + (50,))


def draw_label(tile, text, cx, y, font, max_w):
    d = ImageDraw.Draw(tile, "RGBA")
    # wrap to ~max_w
    words = text.split()
    lines, cur = [], ""
    for wd in words:
        t = (cur + " " + wd).strip()
        if d.textlength(t, font=font) <= max_w or not cur:
            cur = t
        else:
            lines.append(cur); cur = wd
    if cur:
        lines.append(cur)
    lh = font.getbbox("Ay")[3] + 6
    for i, ln in enumerate(lines):
        w = d.textlength(ln, font=font)
        yy = y + i * lh
        d.text((cx - w/2 + 2, yy + 2), ln, font=font, fill=(255, 250, 235, 130))  # paper highlight
        d.text((cx - w/2, yy), ln, font=font, fill=INK + (255,))


def render(content_dir, out_dir, use_ai, W, H):
    data = load_data(content_dir)
    cells, node_loc, pos, roads, M, cw, ch, cell_pos = layout(data, W, H)
    locs = {l["id"]: l for l in data["locations"]}
    os.makedirs(out_dir, exist_ok=True)
    cache = os.path.join(out_dir, "iconcache")

    label_font = load_font(int(min(cw, ch) * 0.058))
    title_font = load_font(int(H * 0.045))
    small_font = load_font(int(min(cw, ch) * 0.036), calligraphic=False)

    # icons per concept
    print("Generating icons (Pollinations pen-and-ink, cached)..." if use_ai
          else "Using procedural fallback icons...")
    icon_cache = {}
    for l in data["locations"]:
        cid, subj = concept_for(l)
        if cid not in icon_cache:
            icon_cache[cid] = get_icon(cid, subj, cache, use_ai)
    for extra, subj in (("compass", "an ornate cartographer compass rose with fleur-de-lis north"),
                        ("monster", "a coiling sea serpent monster"),
                        ("mountains", "a row of small hand drawn mountains"),
                        ("skull", "a small skull and crossbones warning symbol"),):
        icon_cache[extra] = get_icon(extra, subj, cache, use_ai,
                                     size=520 if extra == "compass" else 360)
    banner_font = load_font(int(min(cw, ch) * 0.062))

    meta = {"width": W, "height": H, "base": "base.jpg", "frame": "frame.png",
            "locations": [], "roads": [], "building": None, "legend": [],
            "regions": [], "markers": []}

    # ---- base (opaque bottom layer -> JPEG to keep it light for the browser) ----
    base = parchment(W, H)
    draw_rivers(base, W, H)
    base.convert("RGB").save(os.path.join(out_dir, "base.jpg"), quality=82, optimize=True)

    # ---- roads (each its own tile) ----
    for r in roads:
        a = pos[r["from"]]; b = pos[r["to"]]
        pts = wobble(a, b, min(cw, ch) * 0.04, 14, r["id"])
        xs = [p[0] for p in pts]; ys = [p[1] for p in pts]
        pad = 30
        bx0, by0 = min(xs) - pad, min(ys) - pad
        bx1, by1 = max(xs) + pad, max(ys) + pad
        tw, th = int(bx1 - bx0), int(by1 - by0)
        tile = Image.new("RGBA", (tw, th), (0, 0, 0, 0))
        td = ImageDraw.Draw(tile, "RGBA")
        local = [(x - bx0, y - by0) for x, y in pts]
        dashed = r.get("intercell")
        width = 7 if r.get("intercell") else 5
        td.line(local, fill=INK_SOFT + (150,), width=width + 6, joint="curve")
        td.line(local, fill=INK + (230,), width=width, joint="curve")
        tile.save(os.path.join(out_dir, r["id"] + ".png"))
        meta["roads"].append({"id": r["id"], "from": r["from"], "to": r["to"],
                              "label": r.get("label", ""),
                              "tile": r["id"] + ".png", "bbox": [int(bx0), int(by0), tw, th],
                              "polygon": [[round(x, 1), round(y, 1)] for x, y in pts]})

    # ---- locations (every location is a single illustrated place) ----
    for l in data["locations"]:
        cx, cy = pos[l["id"]]
        cid, _ = concept_for(l)
        T = int(min(cw, ch) * 0.46)
        tile = Image.new("RGBA", (T, T), (0, 0, 0, 0))
        lcx, lcy = T / 2, T * 0.42
        R = T * 0.3
        terrain_patch(tile, cid, lcx, lcy, R)
        icon = icon_cache[cid].resize((int(R * 1.8), int(R * 1.8)))
        tile.alpha_composite(icon, (int(lcx - R * 0.9), int(lcy - R * 0.9)))
        draw_label(tile, l.get("name") or l["id"], lcx, lcy + R * 1.0, label_font, T * 0.92)
        bx, by = int(cx - T / 2), int(cy - T / 2)
        tile.save(os.path.join(out_dir, f"loc-{l['id']}.png"))
        meta["locations"].append({
            "id": l["id"], "name": l.get("name") or l["id"], "cell": l.get("cell"),
            "x": round(cx, 1), "y": round(cy, 1), "concept": cid,
            "tile": f"loc-{l['id']}.png", "bbox": [bx, by, T, T],
            "reveal_nodes": [n["id"] for n in data["nodes"] if n.get("location") == l["id"]],
        })

    # ---- region banners (shown once any place in that region is discovered) ----
    locs_by_cell = {}
    for l in data["locations"]:
        locs_by_cell.setdefault(l.get("cell"), []).append(l["id"])
    for cid, c in cells.items():
        name = c.get("name") or cid
        cx, cy = cell_pos[cid]
        ban = draw_banner(name, banner_font)
        bw, bh = ban.size
        ys = [pos[lid][1] for lid in locs_by_cell.get(cid, []) if lid in pos]
        by = int(max(M * 0.6, (min(ys) if ys else cy) - bh - int(min(cw, ch) * 0.16)))
        bx = int(cx - bw / 2)
        ban.save(os.path.join(out_dir, f"region-{cid}.png"))
        meta["regions"].append({"cell": cid, "name": name, "tile": f"region-{cid}.png",
                                "bbox": [bx, by, bw, bh],
                                "reveal_locations": locs_by_cell.get(cid, [])})

    # ---- markers: a skull at death spots, an X at the Malmö-crossing ending ----
    skull = icon_cache["skull"]
    msz = int(min(cw, ch) * 0.16)
    for n in data["nodes"]:
        if not (n.get("type") == "death" or n.get("is_death")):
            continue
        loc = n.get("location")
        if loc not in pos:
            continue
        mx, my, rev = pos[loc][0], pos[loc][1], {"reveal_location": loc}
        skull.resize((msz, msz)).save(os.path.join(out_dir, f"marker-skull-{n['id']}.png"))
        meta["markers"].append({"type": "skull", "node": n["id"],
                                "tile": f"marker-skull-{n['id']}.png",
                                "bbox": [int(mx - msz / 2), int(my - msz * 0.85), msz, msz], **rev})
    end = next((n for n in data["nodes"] if n.get("type") == "ending"), None)
    if end and end.get("location") in pos:
        ex, ey = pos[end["location"]]
        xs = int(min(cw, ch) * 0.13)
        xt = Image.new("RGBA", (xs, xs), (0, 0, 0, 0))
        xd = ImageDraw.Draw(xt, "RGBA")
        for p in ([(6, 6), (xs - 6, xs - 6)], [(xs - 6, 6), (6, xs - 6)]):
            xd.line(p, fill=(150, 40, 24, 255), width=max(5, xs // 13))
        xt.save(os.path.join(out_dir, "marker-ending.png"))
        meta["markers"].append({"type": "ending", "node": end["id"], "tile": "marker-ending.png",
                                "bbox": [int(ex - xs / 2), int(ey - xs / 2), xs, xs],
                                "reveal_location": "malmo-harbor"})

    # ---- frame: border, compass, title, legend ----
    frame = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    fd = ImageDraw.Draw(frame, "RGBA")
    for off, wd in ((M * 0.45, 8), (M * 0.55, 3)):
        fd.rectangle([off, off, W - off, H - off], outline=INK + (255,), width=int(wd))
    # compass (top-right)
    comp = icon_cache.get("compass")
    if comp:
        cs = int(min(cw, ch) * 0.5)
        frame.alpha_composite(comp.resize((cs, cs)), (int(W - M * 0.6 - cs), int(M * 0.6)))
    # sea monster (bottom area, near Malmö/water)
    mon = icon_cache.get("monster")
    if mon:
        ms = int(min(cw, ch) * 0.5)
        frame.alpha_composite(mon.resize((ms, ms)), (int(M * 0.7), int(H - M * 0.7 - ms)))
    # title cartouche
    title = "Karta över Skåne  ·  Anno 1992"
    tw = title_font.getlength(title)
    tx, ty = W / 2 - tw / 2, M * 0.5
    fd.rounded_rectangle([tx - 40, ty - 14, tx + tw + 40, ty + title_font.size + 18],
                         radius=18, fill=PARCH + (235,), outline=INK + (255,), width=4)
    fd.text((tx, ty), title, font=title_font, fill=INK + (255,))
    # legend (bottom-right)
    legend_items = [("school", "School / building"), ("church", "Church"),
                    ("harbour", "Harbour & sea"), ("forest", "Woods"),
                    ("castle", "Castle"), ("cemetery", "Cemetery"),
                    ("station", "Station"), ("village", "Village / town")]
    lx, ly = int(W - M * 0.6 - cw * 0.9), int(H - M * 0.6 - ch * 0.95)
    lw, lh = int(cw * 0.9), int(ch * 0.95)
    fd.rounded_rectangle([lx, ly, lx + lw, ly + lh], radius=16,
                         fill=PARCH + (228,), outline=INK + (255,), width=4)
    fd.text((lx + 24, ly + 14), "Legend", font=load_font(int(lh * 0.11)), fill=INK + (255,))
    row = ly + int(lh * 0.2)
    step = int((lh - lh * 0.2) / len(legend_items))
    isz = int(step * 0.78)
    for cid, name in legend_items:
        ic = icon_cache.get(cid)
        if ic:
            frame.alpha_composite(ic.resize((isz, isz)), (int(lx + 22), int(row)))
        fd.text((lx + 28 + isz, row + isz * 0.3), name, font=small_font, fill=INK + (255,))
        meta["legend"].append({"concept": cid, "label": name})
        row += step
    frame.save(os.path.join(out_dir, "frame.png"))

    with open(os.path.join(out_dir, "world-map.meta.json"), "w", encoding="utf-8") as fh:
        json.dump(meta, fh, ensure_ascii=False, indent=2)

    # a flattened preview for eyeballing
    preview = base.copy()
    for r in meta["roads"]:
        t = Image.open(os.path.join(out_dir, r["tile"])); preview.alpha_composite(t, (r["bbox"][0], r["bbox"][1]))
    for l in meta["locations"]:
        t = Image.open(os.path.join(out_dir, l["tile"])); preview.alpha_composite(t, (l["bbox"][0], l["bbox"][1]))
    for grp in (meta["regions"], meta["markers"]):
        for it in grp:
            t = Image.open(os.path.join(out_dir, it["tile"])); preview.alpha_composite(t, (it["bbox"][0], it["bbox"][1]))
    preview.alpha_composite(frame, (0, 0))
    flat = preview.convert("RGB")
    flat.save(os.path.join(out_dir, "preview.png"))
    # a small committed thumbnail for the in-game "Map" button
    tw = 640
    flat.resize((tw, int(H * tw / W))).save(
        os.path.join(out_dir, "thumb.jpg"), quality=82, optimize=True)

    print(f"Wrote {len(meta['locations'])} locations, {len(meta['roads'])} roads "
          f"to {out_dir}\n  open {os.path.join(out_dir, 'preview.png')} to eyeball it.")


def main():
    ap = argparse.ArgumentParser(description="Render the OneLife world map.")
    ap.add_argument("--content", help="game-data dir")
    ap.add_argument("--out", default=os.path.join(HERE, "..", "..", "..", "web", "public", "worldmap"))
    ap.add_argument("--no-ai", action="store_true", help="procedural icons only (offline)")
    ap.add_argument("--size", default="3200x2400", help="canvas WxH")
    a = ap.parse_args()
    W, H = (int(v) for v in a.size.lower().split("x"))
    content = find_content_dir(a.content)
    out = os.path.abspath(a.out)
    print(f"content: {content}\nout:     {out}")
    render(content, out, not a.no_ai, W, H)


if __name__ == "__main__":
    main()
