def concept_for(loc):
    text = ((loc.get("name") or "") + " " + (loc.get("description") or "")).lower()
    for kws, cid, subj in CONCEPTS:
        if any(k in text for k in kws):
            return cid, subj
    return "house", "a small lone cottage"


def _seed(s):
    return int(hashlib.md5(s.encode()).hexdigest()[:8], 16)


