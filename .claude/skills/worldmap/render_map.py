def wobble(p0, p1, amp, segs, seed):
    """A hand-drawn jittered polyline between two points (deterministic)."""
    rnd = _seed(seed)
    x0, y0 = p0; x1, y1 = p1
    dx, dy = x1 - x0, y1 - y0
    L = math.hypot(dx, dy) or 1
    nx, ny = -dy / L, dx / L
    pts = []
    for i in range(segs + 1):
        t = i / segs
        rnd = (rnd * 1103515245 + 12345) & 0x7FFFFFFF
        j = 0 if i in (0, segs) else (rnd / 0x7FFFFFFF - 0.5) * 2 * amp
        pts.append((x0 + dx * t + nx * j, y0 + dy * t + ny * j))
    return pts


