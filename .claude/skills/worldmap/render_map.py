#!/usr/bin/env python3
"""Render the OneLife world as a vintage fantasy map (Middle-earth style):
layered PNGs + a coordinate metadata file + a legend.

It reads the YAML game-data (the same files the engine seeds), lays the places
out deterministically on a grid (so coordinates are exact), draws aged parchment,
ink coastline/forest/field terrain, hand-inked roads, a compass rose, a title
cartouche and a legend, and places a pen-and-ink icon per location (generated by
the free Pollinations image provider, cached, with a procedural fallback).

Output is a STACK of PNG layers so the game can reveal it place-by-place
(fog of war):
  base.png         always-on parchment canvas
  loc-<id>.png      one transparent tile per location  (icon + label + terrain)
  road-<id>.png     one transparent tile per road
  room-<nodeid>.png the school's interior nodes, drawn as rooms
  frame.png         border + compass + title + legend (always on top)
  world-map.meta.json   pixel positions of every place + road polygons + tile bboxes

Usage:
  python render_map.py [--out DIR] [--content DIR] [--no-ai] [--size WxH]
--content defaults to $GAME_DATA_DIR, then $CONTENT_DIR, then ../OneLife-KBK-mystery
--out defaults to ../../web/public/worldmap (relative to this script)
"""
